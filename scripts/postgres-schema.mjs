import { readFile, mkdir, writeFile } from "node:fs/promises";

// Keep one model definition: local SQLite and hosted PostgreSQL share the models.
const source = await readFile(
  new URL("../apps/api/prisma/schema.prisma", import.meta.url),
  "utf8",
);
const schema = source.replace('provider = "sqlite"', 'provider = "postgresql"');
if (schema === source) throw new Error("Expected the canonical SQLite schema.");
const directory = new URL("../apps/api/prisma-postgres/", import.meta.url);
await mkdir(directory, { recursive: true });
await writeFile(
  new URL("schema.prisma", directory),
  `// Generated by scripts/postgres-schema.mjs. Edit prisma/schema.prisma instead.\n${schema}`,
);
