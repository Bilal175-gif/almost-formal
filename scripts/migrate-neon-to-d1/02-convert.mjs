// Convert Neon CSV exports (01-export.sh) into D1 INSERT SQL.
//
// Usage:
//   node scripts/migrate-neon-to-d1/02-convert.mjs ./neon-export ./d1-import.sql
//
// Rules:
// - Tables in dependency order (same order as 01-export.sh).
// - Empty CSV field -> NULL. PostgreSQL booleans t/f -> 1/0.
// - Timestamps pass through as ISO strings (D1 stores TEXT); psql
//   exports them like "2026-11-14 04:25:30.123+05" — normalised here
//   to UTC ISO ("2026-11-13T23:25:30.123Z") so Prisma reads them back
//   as the same instants.
// - Strings are single-quote escaped ('' doubling). No value is
//   ever interpolated without escaping.
// - Output is a plain .sql file: review it, then apply to the REMOTE
//   D1 only after a local-D1 dry run:
//     wrangler d1 execute almost-formal-db --local --file=d1-import.sql
//     wrangler d1 execute almost-formal-db --remote --file=d1-import.sql
//   D1 has a 100-statement batch limit per execute call; if the file
//   is large, split it (the script writes one statement per line, so
//   `split -l 90` works) and apply the chunks in order.
import { readFileSync, writeFileSync } from "node:fs";

const [inDir, outFile] = process.argv.slice(2);
if (!inDir || !outFile) {
  console.error(
    "Usage: node scripts/migrate-neon-to-d1/02-convert.mjs <csv-dir> <out.sql>",
  );
  process.exit(1);
}

// table -> [boolean columns]
const TABLES = [
  ["StoreSettings", ["codEnabled"]],
  ["User", []],
  ["Admin", []],
  ["Category", []],
  ["Product", ["featured", "archived"]],
  ["ProductImage", []],
  ["ProductCategory", []],
  ["Address", []],
  ["Cart", []],
  ["CartItem", []],
  ["Wishlist", []],
  ["WishlistItem", []],
  ["Order", []],
  ["OrderItem", []],
  ["Payment", []],
  ["Shipment", []],
  ["InventoryMovement", []],
  ["AuditLog", []],
  ["Subscriber", []],
  ["ContactMessage", []],
];

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i++;
        } else quoted = false;
      } else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") {
      row.push(field);
      field = "";
    } else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      field = "";
      rows.push(row);
      row = [];
    } else field += ch;
  }
  if (field !== "" || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows.filter((r) => r.length > 1 || r[0] !== "");
}

function toIso(value) {
  // "2026-11-14 04:25:30.123+05" -> "2026-11-13T23:25:30.123Z"
  const d = new Date(value.replace(" ", "T"));
  return Number.isNaN(d.getTime()) ? value : d.toISOString();
}

const out = [
  "-- Neon -> D1 import. Generated by scripts/migrate-neon-to-d1/02-convert.mjs.",
  "-- Apply ONLY to an empty D1 (migrations already applied). Do not re-run on a live D1.",
  "-- Review counts per table against the export log before applying.",
];
for (const [table, boolCols] of TABLES) {
  const csv = readFileSync(`${inDir}/${table}.csv`, "utf8");
  const rows = parseCsv(csv);
  const header = rows.shift();
  if (!header) continue;
  let count = 0;
  for (const values of rows) {
    const literals = values.map((value, i) => {
      const col = header[i];
      if (value === "") return "NULL";
      if (boolCols.includes(col)) return value === "t" ? "1" : "0";
      if (/^\d{4}-\d{2}-\d{2} /.test(value))
        return `'${toIso(value).replace(/'/g, "''")}'`;
      if (/^-?\d+(\.\d+)?$/.test(value) && col !== "phone" && col !== "postalCode")
        return value;
      return `'${value.replace(/'/g, "''")}'`;
    });
    out.push(
      `INSERT INTO "${table}" (${header.map((c) => `"${c}"`).join(",")}) VALUES (${literals.join(",")});`,
    );
    count++;
  }
  out.push(`-- ${table}: ${count} rows`);
}
writeFileSync(outFile, out.join("\n") + "\n");
console.log(`Wrote ${outFile} (${out.length} lines).`);
